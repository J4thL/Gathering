// crystal_sprite.hpp - the snowfield's ice crystal (a hand-drawn 28x32 sprite). '.' is empty, 0-5 index the palette.
#pragma once
#include "core/gfx.hpp"

inline Img mkCrystal() {
    static const u32 PAL[] = {
    HEX(0x3063bc),
    HEX(0xe6feff),
    HEX(0x32dde7),
    HEX(0x3cade9),
    HEX(0x6b72e6),
    HEX(0x9538e1)};
    static const char* const ROWS[32] = {
    ".............0..............",
    "............010.............",
    "............010.............",
    "...........01210............",
    "...........012130...........",
    "..........0312210...........",
    "..........03122130..........",
    ".........0331221340.........",
    ".........0312221340.........",
    "........043122221110........",
    ".000....043111111350........",
    ".01100.0111222221440........",
    ".012120015312222340.........",
    ".012212404313222140.....000.",
    ".012221110333223140..000010.",
    ".04122135041322334000221210.",
    ".04111213041323134014112130.",
    ".0512221204312313054122210..",
    ".0041321230332314041211130..",
    "..041332130313310331222140..",
    "..044133130334310313331310..",
    "...04133120314303133334450..",
    "...0441331031440434313400...",
    "....04130000040514313400....",
    "...004005444400044334000....",
    ".003503442222240414000440...",
    ".013044122221114040021130...",
    "04110433111113330004122110..",
    "05220054133331450053122200..",
    ".0400.0043333300..003200....",
    "..0.....003300......00......",
    "..........00................"};
    Img im(28, 32);
    for (int y = 0; y < 32; y++)
        for (int x = 0; x < 28; x++) {
            const char c = ROWS[y][x];
            if (c == '.') continue;
            im.set(x, y, PAL[c <= '9' ? c - '0' : c - 'a' + 10]);
        }
    return im;
}
