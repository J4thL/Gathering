inline Img mkCampFireFrame(int frame) {  // frame -1: the cold fire, frame -2: the cold fire under snow (the snowfield's)
    const char* const* rows = frame < 0 ? campart::coldRows() : campart::litRows(frame);
    Img im(CAMP_FIRE_W, CAMP_FIRE_H);
    for (int y = 0; y < CAMP_FIRE_H; y++)
        for (int x = 0; x < CAMP_FIRE_W; x++)
            if (rows[y][x] != '.') im.set(x, y, campFireColor(rows[y][x]));
    if (frame == -2) {  // snow on every upward-facing edge of the logs, and drifts against the pile
        const u32 W = HEX(0xf4f8fc), W2 = HEX(0xdbe6f2), W3 = HEX(0xb9cce3);
        Img src = im;
        for (int y = 0; y < CAMP_FIRE_H - 1; y++)
            for (int x = 0; x < CAMP_FIRE_W; x++) {
                if (src.get(x, y) == 0 || rows[y][x] == 'k' || rows[y][x] == 'u' || rows[y][x] == 's' || rows[y][x] == 't') continue;  // not ash or charcoal
                if (y == 0 || src.get(x, y - 1) == 0) {
                    im.set(x, y, W);
                    if (y + 1 < CAMP_FIRE_H && src.get(x, y + 1) != 0 && (x & 1)) im.set(x, y + 1, W2);
                }
            }
        for (int x = 0; x < CAMP_FIRE_W; x++)
            if (src.get(x, 27) == 0 && (x < 5 || x > 10)) im.set(x, 27, (x & 1) ? W2 : W);
        im.rect(0, 26, 2, 1, W2); im.rect(14, 26, 2, 1, W3); im.rect(1, 27, 3, 1, W); im.rect(12, 27, 3, 1, W2);
    }
    return im;
}
