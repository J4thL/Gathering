// camp_fire_art.hpp - the campfire of the abandoned camps: a lit one (16 frames of flame, hand-drawn, about 12 frames a second) and the cold
// one it starts as (a teepee of burnt logs over ash, drawn with the same base rows as the flame so the lighting looks seamless).
// 16 x 28, the logs on the bottom rows. Rows of palette letters, '.' is transparent. Needs Img and HEX from the includes before it.
#pragma once

constexpr int CAMP_FIRE_FRAMES = 16;
constexpr int CAMP_FIRE_W = 16, CAMP_FIRE_H = 28;

inline u32 campFireColor(char c) {
    switch (c) {
        case 'a': return HEX(0xc44618);
        case 'b': return HEX(0xf6c216);
        case 'c': return HEX(0xe66612);
        case 'd': return HEX(0xfbecbc);
        case 'e': return HEX(0x40261e);
        case 'f': return HEX(0x84543a);
        case 'g': return HEX(0x603a2c);
        case 'h': return HEX(0x2a1a18);
        case 'k': return HEX(0x1a1416);
        case 'u': return HEX(0x4a4448);
        case 's': return HEX(0x706a6e);
        case 't': return HEX(0x9e989a);
        default: return 0;
    }
}

