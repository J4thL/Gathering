inline Img mkRockArt(const RockArt& a, int theme = 0) {
    const u32* pal = ROCK_PALS[theme];
    Img im(a.w, a.h);
    for (int y = 0; y < a.h; y++)
        for (int x = 0; x < a.w; x++)
            if (a.rows[y][x] != '.') im.set(x, y, pal[a.rows[y][x] - 'a']);
    return im;
}
// Recolours a grey picture (the rubble of a broken rock) into a theme: the brightness of each pixel picks a spot along the palette.
inline Img retintRock(const Img& src, int theme) {
    if (theme == 0) return src;
    const u32* pal = ROCK_PALS[theme];
    Img im = src;
    for (int y = 0; y < im.h; y++)
        for (int x = 0; x < im.w; x++) {
            const u32 c = im.get(x, y);
            if (cA(c) == 0) continue;
            float t = ((cR(c) * 0.30f + cG(c) * 0.59f + cB(c) * 0.11f) - 40.f) / (198.f - 40.f);
            t = t < 0.f ? 0.f : t > 1.f ? 1.f : t;
            const float pos = t * 3.f;
            const int i = pos >= 3.f ? 2 : (int)pos;
            const float f = pos - i;
            auto mix = [&](u32 a, u32 b, int sh) { return (int)(((a >> sh) & 255) * (1.f - f) + ((b >> sh) & 255) * f); };
            im.set(x, y, RGBA(mix(pal[i], pal[i + 1], 16), mix(pal[i], pal[i + 1], 8), mix(pal[i], pal[i + 1], 0), cA(c)));
        }
    return im;
}

