inline Img mkSnowBirchFrame(int frame) {
    Img im(SNOW_BIRCH_W, SNOW_BIRCH_H);
    for (int y = 0; y < SNOW_BIRCH_H; y++) {
        const char* row = SNOW_BIRCH_F[(frame % SNOW_BIRCH_FRAMES) * SNOW_BIRCH_H + y];
        for (int x = 0; x < SNOW_BIRCH_W; x++)
            if (row[x] != '.') im.set(x, y, SNOW_BIRCH_PAL[row[x] - 'a']);
    }
    return im;
}
