inline Img mkSnowSpruceFrame(int frame) {
    Img im(SNOW_SPRUCE_W, SNOW_SPRUCE_H);
    for (int y = 0; y < SNOW_SPRUCE_H; y++) {
        const char* row = SNOW_SPRUCE_F[(frame % SNOW_SPRUCE_FRAMES) * SNOW_SPRUCE_H + y];
        for (int x = 0; x < SNOW_SPRUCE_W; x++)
            if (row[x] != '.') im.set(x, y, SNOW_SPRUCE_PAL[row[x] - 'a']);
    }
    return im;
}
