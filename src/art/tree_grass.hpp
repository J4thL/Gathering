struct GrassSet { int w, h, ax, ay; const u32* pal; const char* const* rows; };  // ax, ay = the foot of the trunk
static const GrassSet GRASS_SET[GRASS_SETS] = {
    {28, 9, 12, 6, GRASS_P_OAK, GRASS_F_OAK},  // oak
    {51, 9, 38, 9, GRASS_P_OLD, GRASS_F_OLD},  // old
    {16, 7, 6, 4, GRASS_P_SAPLING, GRASS_F_SAPLING},  // sapling
    {25, 10, 11, 7, GRASS_P_DEAD, GRASS_F_DEAD},  // dead
    {22, 8, 9, 6, GRASS_P_SPRUCE, GRASS_F_SPRUCE},  // spruce
};

inline Img mkGrassFrame(int set, int frame) {
    const GrassSet& g = GRASS_SET[set];
    Img im(g.w, g.h);
    for (int y = 0; y < g.h; y++) {
        const char* row = g.rows[(frame % GRASS_FRAMES) * g.h + y];
        for (int x = 0; x < g.w; x++)
            if (row[x] != '.') im.set(x, y, g.pal[row[x] - 'a']);
    }
    return im;
}
