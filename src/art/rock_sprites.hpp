inline Img mkRockArt(const RockArt& a) {
    Img im(a.w, a.h);
    for (int y = 0; y < a.h; y++)
        for (int x = 0; x < a.w; x++)
            if (a.rows[y][x] != '.') im.set(x, y, ROCK_PAL[a.rows[y][x] - 'a']);
    return im;
}
