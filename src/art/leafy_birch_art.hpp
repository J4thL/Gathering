inline Img mkLeafyBirchFrame(int frame) {
    Img im(LEAFY_BIRCH_W, LEAFY_BIRCH_H);
    const char* const* rows = birchart::F + (size_t)((frame % LEAFY_BIRCH_FRAMES + LEAFY_BIRCH_FRAMES) % LEAFY_BIRCH_FRAMES) * LEAFY_BIRCH_H;
    for (int y = 0; y < LEAFY_BIRCH_H; y++)
        for (int x = 0; x < LEAFY_BIRCH_W; x++)
            if (rows[y][x] != '.') im.set(x, y, leafyBirchColor(rows[y][x]));
    return im;
}
