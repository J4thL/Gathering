inline u32 leafyBirchColor(char c) {
    switch (c) {
        case 'a': return HEX(0xffffff);
        case 'b': return HEX(0xf2f8fe);
        case 'c': return HEX(0x15593e);
        case 'd': return HEX(0xe2effb);
        case 'e': return HEX(0x082a24);
        case 'f': return HEX(0x1b1e22);
        case 'g': return HEX(0x292830);
        case 'h': return HEX(0x1a1c21);
        case 'i': return HEX(0x152827);
        case 'j': return HEX(0xeadadb);
        case 'k': return HEX(0xfdf5e1);
        case 'l': return HEX(0x83737f);
        default: return 0;
    }
}

