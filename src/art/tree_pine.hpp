inline Img mkPineFrame(int frame) {
    Img im(PINE_W, PINE_H);
    for (int y = 0; y < PINE_H; y++) {
        const char* row = PINE_F[(frame % PINE_FRAMES) * PINE_H + y];
        for (int x = 0; x < PINE_W; x++)
            if (row[x] != '.') im.set(x, y, PINE_PAL[row[x] - 'a']);
    }
    return im;
}
