// decor rocks: a cool weathered grey-taupe, clearly different from the minable ones
static const u32 DROCK_DECOR_PAL[5] = {HEX(0x383236), HEX(0x5e5658), HEX(0x867c78), HEX(0xa69a92), HEX(0xc0b4aa)};
inline Img mkPalArt(const RockArt& a, const u32* pal) {
    Img im(a.w, a.h);
    for (int y = 0; y < a.h; y++)
        for (int x = 0; x < a.w; x++)
            if (a.rows[y][x] != '.') im.set(x, y, pal[a.rows[y][x] - 'a']);
    return im;
}
